Chinese* findChinese(char ch[]){
	int len=sizeof(ch_16x16)/sizeof(ch_16x16[0]);
	for(int i=0;i<len;i++){
		if(strcmp(ch_16x16[i].id,ch)==0){
			return &ch_16x16[i];
		}
	}
	return NULL;
}













